    updated_at = now()
FROM sheet_order o
WHERE t.is_deleted = false
  AND t.service_type IN ('Procedure', 'Injection', 'File')
  AND o.kind = 'test'
  AND lower(regexp_replace(t.name, '[^A-Za-z0-9]', '', 'g')) = o.match_key;

-- Sheet rows that matched nothing in HMS (expected: none).
SELECT o.kind, o.name, o.sort_order
FROM sheet_order o
WHERE NOT EXISTS (
          SELECT 1 FROM masters.diagnostic_services s
          WHERE s.is_deleted = false
            AND lower(regexp_replace(s.name, '[^A-Za-z0-9]', '', 'g')) = o.match_key
            AND ((o.kind = 'radiology' AND s.service_type = 'Radiology')
              OR (o.kind IN ('lab', 'outsourced') AND s.service_type = 'Laboratory' AND s.is_outsourced = (o.kind = 'outsourced'))))
  AND NOT EXISTS (
          SELECT 1 FROM masters.diagnostic_packages p
          WHERE o.kind = 'package' AND p.is_deleted = false AND lower(regexp_replace(p.name, '[^A-Za-z0-9]', '', 'g')) = o.match_key)
  AND NOT EXISTS (
          SELECT 1 FROM masters.diagnostic_tests t
          WHERE o.kind = 'test' AND t.is_deleted = false AND t.service_type IN ('Procedure', 'Injection', 'File')
            AND lower(regexp_replace(t.name, '[^A-Za-z0-9]', '', 'g')) = o.match_key)
ORDER BY o.sort_order;

