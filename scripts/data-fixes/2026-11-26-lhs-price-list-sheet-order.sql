-- 1. Lab tests — in-house and outsourced kept apart.
UPDATE masters.diagnostic_services s
SET sample_type = o.sample,
    sort_order = o.sort_order,
    updated_at = now()
FROM sheet_order o
WHERE s.is_deleted = false
  AND s.service_type = 'Laboratory'
  AND o.kind = CASE WHEN s.is_outsourced THEN 'outsourced' ELSE 'lab' END
  AND lower(regexp_replace(s.name, '[^A-Za-z0-9]', '', 'g')) = o.match_key;

